
from pathlib import Path

from src.generate_data import save_customer_data
from src.preprocessing import preprocess_customer_data

from src.clustering import train_customer_clusters

from src.cluster_comparison import (
    compare_cluster_counts,
    plot_cluster_comparison,
)

from src.dbscan_experiment import (
    run_dbscan,
    analyse_dbscan_results,
)

from src.anomaly_detection import detect_anomalies

from src.dimensionality_reduction import (
    run_pca,
    plot_pca,
)


PROJECT_ROOT = Path(__file__).resolve().parent
DATA_DIR = PROJECT_ROOT / "data"


def main():

    print("=" * 60)
    print("CUSTOMER SEGMENTATION - UNSUPERVISED LEARNING")
    print("=" * 60)

    # 1. Generate customer dataset
    customers = save_customer_data()

    # 2. Preprocess and scale features
    customers, scaled_features, scaler = preprocess_customer_data()

    # 3. K-Means clustering
    print("\n" + "=" * 60)
    print("K-MEANS CLUSTERING")
    print("=" * 60)

    clustered_customers, kmeans_model, kmeans_scaler = (
        train_customer_clusters(customers)
    )

    # Retrieve the cluster labels generated by K-Means
    kmeans_labels = kmeans_model.labels_

    # 4. Compare different numbers of clusters
    print("\n" + "=" * 60)
    print("CLUSTER COUNT COMPARISON")
    print("=" * 60)

    comparison = compare_cluster_counts(
        scaled_features,
        min_clusters=2,
        max_clusters=7,
    )

    print("\nCluster comparison results:")
    print(comparison.to_string(index=False))

    plot_cluster_comparison(comparison)

    # 5. DBSCAN experiment
    print("\n" + "=" * 60)
    print("DBSCAN EXPERIMENT")
    print("=" * 60)

    dbscan_model, dbscan_labels = run_dbscan(
        scaled_features,
        eps=0.8,
        min_samples=5,
    )

    dbscan_results = analyse_dbscan_results(
        customers,
        dbscan_labels,
    )

    # 6. Anomaly detection
    print("\n" + "=" * 60)
    print("ANOMALY DETECTION")
    print("=" * 60)

    isolation_model, anomaly_results = detect_anomalies(
        customers,
        scaled_features,
        contamination=0.05,
    )

    # 7. PCA dimensionality reduction
    print("\n" + "=" * 60)
    print("PRINCIPAL COMPONENT ANALYSIS")
    print("=" * 60)

    pca_model, reduced_features = run_pca(
        scaled_features,
        n_components=2,
    )

    plot_pca(
        reduced_features,
        labels=kmeans_labels,
    )

    # 8. Save experiment results
    clustered_customers.to_csv(
        DATA_DIR / "kmeans_results.csv",
        index=False,
    )

    dbscan_results.to_csv(
        DATA_DIR / "dbscan_results.csv",
        index=False,
    )

    anomaly_results.to_csv(
        DATA_DIR / "anomaly_detection_results.csv",
        index=False,
    )

    comparison.to_csv(
        DATA_DIR / "cluster_comparison_results.csv",
        index=False,
    )

    print("\n" + "=" * 60)
    print("ALL EXPERIMENTS COMPLETED SUCCESSFULLY")
    print("=" * 60)


if __name__ == "__main__":
    main()
